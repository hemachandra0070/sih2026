export function getSchemeById(id: string): Scheme | undefined {
  const normalizedId = id === "NSFDC-MF" ? "NSFDC-MFS" : id;
  return mockSchemes.find(
    (s) => s.id === normalizedId || s.schemeId === normalizedId || s.id === id || s.schemeId === id
  );
}

export function getSchemesByPurpose(purpose: "business" | "education"): Scheme[] {
  return mockSchemes.filter((s) => s.purpose === purpose || s.purpose === "both");
}